import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  Document,
  HeadingLevel,
  Packer,
  Paragraph,
  TextRun,
} from "docx";

const title = "红伞";

const story = `凌晨两点十七分，林澈的手机震了一下。

屏幕亮起，一条陌生短信只有四个字：别回消息。

他皱眉，正要关屏，第二条又弹出来：你现在窗边吗？

林澈住在十二楼，窗外是沉下去的城市，路灯把雨后的人行道照得像刚擦过的玻璃。他没走到窗边，只把窗帘掀开一角。楼下的便利店还亮着，自动门开合，像一只疲倦的眼睛。

第三条短信到来：如果你看见一个拿着红伞的人，别让他进门。

林澈的背脊起了一层薄汗。红伞？这么晚谁会打伞？他把手机放到桌上，告诉自己别被恶作剧吓到。可是心跳不肯配合，敲得胸口发空。

门铃忽然响了。

短促、坚定，像有人不打算离开。

林澈走到猫眼前。走廊的感应灯亮着，光线冷白，照出一个人影：黑色外套，手里竟真的握着一把收拢的红伞，伞尖还滴着水。

他握住门把的手停住了。

手机又震：别开。

林澈咽了口唾沫，压低声音问：“谁？”

门外的人隔着门板说：“送错了。麻烦开一下，我把东西拿回去。”

声音很平常，甚至有点疲惫，像每个夜班快递员。林澈的理智开始反驳：也许真的送错，也许红伞只是巧合。可那条短信像钉子一样钉在他脑子里。

他退后一步，打开门口的智能门铃摄像头回放。画面里，走廊的镜头捕捉到门外的人——但他身后还有第二个影子，贴在墙上，扁平得不合理，像被灯光压得太薄。那影子没有伞，却在慢慢抬手，手指的形状从墙面里“长”出来。

林澈的喉咙发紧。他关掉回放，盯着门缝下方。那条缝里没有任何脚步的移动声，可滴水声还在。

门铃又响一次。

“开门。”门外的人这次没再客气。

林澈后退到玄关，抓起一旁的雨伞——一把普通的黑伞。他突然想起短信里的规则：别让拿红伞的人进门。那是不是意味着，只要他不“进门”，一切都安全？或者……进门的不一定是他。

他深吸一口气，打开门边的链条锁，把门拉开一道仅容手伸出的缝。

走廊里的空气像冰。红伞的伞布在灯下红得刺眼。门外的人抬头，露出一张温和到几乎没有表情的脸：“谢谢，东西——”

林澈没等他说完，把黑伞猛地从门缝里伸出去，伞尖对准那把红伞的伞柄，用力一挑。

红伞“啪”地一下弹开。

伞面撑开的瞬间，走廊里所有的灯同时熄灭。黑暗像一口井罩下来，连呼吸都被吞掉。林澈听见“咔嗒”一声，像什么东西落在地上，又像门锁自动转动。

手机在桌上发出最后一次震动，屏幕自动亮起，在黑暗里像一块冷白的骨头。

短信只有一句：你看见了吗？红伞打开时，门就不是你的门了。

林澈僵在原地。门缝外的黑暗里，响起伞骨轻微摩擦的声响，仿佛有人在慢慢收伞，也仿佛有人在慢慢展开别的东西。

他想把门关上，却发现链条锁不知何时已经解开。门把手开始自己向下压。

就在门即将被推开的那一刻，楼下便利店的自动门“叮咚”一声。那声响像远处的灯塔，穿过一层层楼板爬上来。

林澈猛地想起一个更简单的规则——如果门不再是你的门，那就别站在门后。

他转身冲进屋里，跑向窗边，拉开窗帘，按下窗户的开启键。冷风灌进来，城市的灯光铺开，像一张巨大的地图。

他没跳，只是把手机举到窗外，像把某种信号抛出去一样，朝楼下的便利店方向按下了拨号键。

电话接通的一瞬间，屋内那扇门“吱呀”打开。黑暗从门口漫进来，像潮水。

电话里传来一个疲惫却清晰的女声：“便利店夜班，有什么需要？”

林澈用尽全身力气，挤出一句：“我需要你……一直跟我说话。别停。”

女声愣了半秒：“好。你现在在哪里？你听得到我吗？”

林澈靠着窗框坐下，背对着门口的黑暗，把目光钉在楼下那片亮光里。电话里，女声开始讲货架、讲雨后进货、讲早晨五点会有第一辆公交经过，讲一切普通到不能再普通的事。

黑暗在门口停住了，像犹豫，像在倾听。

林澈终于明白：有些东西不是害怕光，而是害怕人间的琐碎——害怕有人用平常的声音，把你从一扇不属于你的门里，拉回你自己的生活。

他把额头抵在玻璃上，听着电话里持续的絮语，直到天边泛起一点点灰白。滴答声在口袋里响起——他这才发现，自己今晚出门没带钥匙，却带着父亲留下的那块旧怀表。

指针走得很慢，但在走。`;

const outDir = join(process.cwd(), "output");
mkdirSync(outDir, { recursive: true });

const paragraphs = [];

paragraphs.push(
  new Paragraph({
    heading: HeadingLevel.TITLE,
    children: [new TextRun({ text: title })],
  })
);

for (const block of story.split(/\n\n+/g)) {
  const text = block.trim();
  if (!text) continue;
  paragraphs.push(new Paragraph({ children: [new TextRun(text)] }));
}

const doc = new Document({
  sections: [
    {
      properties: {
        page: {
          margin: {
            // Twips: 1440 = 1 inch. Use Word-friendly margins.
            top: 1440,
            right: 1440,
            bottom: 1440,
            left: 1440,
          },
        },
      },
      children: paragraphs,
    },
  ],
});

const buf = await Packer.toBuffer(doc);
const outPath = join(outDir, "story-linche-red-umbrella.docx");
writeFileSync(outPath, buf);

